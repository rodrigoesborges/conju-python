def buscar_dados(codigo, indicador):

    url = (
        f"https://api.worldbank.org/v2/country/{codigo}/indicator/"
        f"{indicador}?date=2016:2025&format=json&per_page=1000"
    )

    resposta = requests.get(url, timeout=30)
