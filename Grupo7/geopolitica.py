import pandas as pd
import requests

# Período de análise
anos = list(range(2016, 2026))

# Economias e códigos do Banco Mundial
economias = {
    "Estados Unidos": "USA",
    "União Europeia": "EUU",
    "China": "CHN",
    "Brasil": "BRA",
    "Mundo": "WLD"
}

# Indicadores do Banco Mundial
indicadores = {
    "PIB (US$ bilhões)": "NY.GDP.MKTP.CD",
    "PIB per capita (US$)": "NY.GDP.PCAP.CD",
    "Crescimento (%)": "NY.GDP.MKTP.KD.ZG"
}

# Função para consultar dados do Banco Mundial
def buscar_dados(codigo, indicador):

    url = (
        f"https://api.worldbank.org/v2/country/{codigo}/indicator/"
        f"{indicador}?date=2016:2025&format=json&per_page=1000"
    )

    resposta = requests.get(url)
    resposta.raise_for_status()

    dados = resposta.json()

    if len(dados) < 2 or dados[1] is None:
        return pd.DataFrame(columns=["Ano", "Valor"])

    registros = []

    for item in dados[1]:
        registros.append({
            "Ano": int(item["date"]),
            "Valor": item["value"]
        })

    return pd.DataFrame(registros)


# Construção da base de dados
resultados = []

for economia, codigo in economias.items():

    tabelas = {}

    for nome, indicador in indicadores.items():
        tabelas[nome] = buscar_dados(codigo, indicador)

    df_economia = pd.DataFrame({"Ano": anos})

    for nome, tabela in tabelas.items():
        df_economia = df_economia.merge(
            tabela,
            on="Ano",
            how="left"
        )

        df_economia.rename(
            columns={"Valor": nome},
            inplace=True
        )

    df_economia["Economia"] = economia

    resultados.append(df_economia)


# Consolidar todos os dados
df = pd.concat(resultados, ignore_index=True)

# PIB em bilhões de dólares
df["PIB (US$ bilhões)"] = (
    df["PIB (US$ bilhões)"] / 1000
).round(2)

# Participação no PIB mundial por ano
pib_mundial = (
    df[df["Economia"] == "Mundo"]
    [["Ano", "PIB (US$ bilhões)"]]
    .rename(columns={
        "PIB (US$ bilhões)": "PIB mundial"
    })
)

df = df.merge(pib_mundial, on="Ano", how="left")

df["Participação mundial (%)"] = (
    df["PIB (US$ bilhões)"] /
    df["PIB mundial"] * 100
).round(2)

# Formatação dos indicadores
df["PIB per capita (US$)"] = (
    df["PIB per capita (US$)"].round(2)
)

df["Crescimento (%)"] = (
    df["Crescimento (%)"].round(2)
)

# Organizar tabela
colunas = [
    "Ano",
    "Economia",
    "PIB (US$ bilhões)",
    "PIB per capita (US$)",
    "Crescimento (%)",
    "Participação mundial (%)"
]

df = df[colunas].sort_values(
    ["Ano", "Economia"]
)

# Exibir comparação anual
print("\nCOMPARAÇÃO DAS ECONOMIAS MUNDIAIS (2016-2025)\n")

print(df.to_string(index=False))


# Ranking das economias por PIB em cada ano
print("\nRANKING DAS MAIORES ECONOMIAS POR ANO\n")

for ano in anos:

    ranking = df[
        (df["Ano"] == ano) &
        (df["Economia"] != "Mundo")
    ].sort_values(
        by="PIB (US$ bilhões)",
        ascending=False
    )

    ranking = ranking.reset_index(drop=True)
    ranking.index += 1

    print(f"\nANO {ano}")
    print(
        ranking[
            ["Economia", "PIB (US$ bilhões)"]
        ].to_string()
    )


# Exportar resultados para Excel
df.to_excel(
    "comparacao_economias_2016_2025.xlsx",
    index=False
)

