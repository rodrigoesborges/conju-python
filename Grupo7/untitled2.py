import requests
import pandas as pd

# =====================================
# 1. CONFIGURAÇÃO
# =====================================

indicador = "GC.NLD.TOTL.GD.ZS"

paises = {
    "USA": "Estados Unidos",
    "CHN": "China",
    "JPN": "Japão",
    "DEU": "Alemanha",
    "IND": "Índia",
    "GBR": "Reino Unido",
    "FRA": "França",
    "ITA": "Itália",
    "BRA": "Brasil",
    "CAN": "Canadá",
    "KOR": "Coreia do Sul",
    "RUS": "Rússia"
}

anos = range(2020, 2025)

# =====================================
# 2. COLETA DOS DADOS
# =====================================

dados = []

for codigo, pais in paises.items():

    url = (
        f"https://api.worldbank.org/v2/country/{codigo}/"
        f"indicator/{indicador}"
        f"?date=2020:2024&format=json&per_page=100"
    )

    resposta = requests.get(url, timeout=30)
    resposta.raise_for_status()

    resultado = resposta.json()

    if resultado[1] is None:
        continue

    for item in resultado[1]:
        dados.append({
            "País": pais,
            "Ano": int(item["date"]),
            "Déficit (% PIB)": item["value"]
        })

df = pd.DataFrame(dados)

# =====================================
# 3. CONSTRUÇÃO DA TABELA
# =====================================

tabela = df.pivot(
    index="País",
    columns="Ano",
    values="Déficit (% PIB)"
)

# Garantir apresentação dos cinco anos
tabela = tabela.reindex(columns=list(anos))

# Ordenação alfabética
tabela = tabela.sort_index()


